// The glassfloor family's editor-record hooks (glassfloorReset, glassfloorUnload and
// glassfloorLoad here): nothing to reset; the model files' models are released; the
// module's model archive is read and each model file's model loaded from it.

// One of the module's model files: its name, the archive it is read from, the
// world slot its clones go into, and the model once loaded.
struct ModelFile {
	const char* name; // 0x00
	void* archive;    // 0x04
	s32 world;        // 0x08
	void* model;      // 0x0C
};

