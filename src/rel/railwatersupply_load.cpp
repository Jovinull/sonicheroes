// The rail water supply's Load hook (railwatersupplyLoad here): the module's
// model archive is read and each model file's model loaded from it (the Reset
// and Unload are in rel/railwatersupply_hooks.cpp).

// One of the module's model files: its name, the archive it is read from, the
// world slot its clones go into, and the model once loaded.
struct ModelFile {
	const char* name; // 0x00
	void* archive;    // 0x04
	s32 world;        // 0x08
	void* model;      // 0x0C
};

extern "C" ModelFile railWaterSupplyModelFiles[2];
extern "C" u8* lbl_8042C1D0;
extern "C" u8* lbl_8042C298;
extern "C" u8 lbl_802FF5A0[];

extern "C" void fn_801A4C84(void* resource);
